// The Wi-Fi extension (F-WIFI, D-18). The image only has main as a package source, and hostapd is in
// universe. So the download adds universe and at the same time forbids everything from it except hostapd:
// nothing else can slip in from universe, neither now nor with a later update.
const (
	wifiSourcesFile = "/etc/apt/sources.list.d/vr-wifi.sources"
	wifiPinFile     = "/etc/apt/preferences.d/vr-wifi"
	// WiFiUnit is the service that runs the access point.
	WiFiUnit = "vr-hostapd.service"
)

// WiFiPackages are the packages of the extension, the same list as image/packages-wifi.txt.
var WiFiPackages = []string{"hostapd", "iw", "wireless-regdb", "rfkill"}

const wifiPin = `# Generated by vanilla-router (D-18). From universe only hostapd may be installed.
Package: *
Pin: release c=universe
Pin-Priority: -1

Package: hostapd
Pin: release c=universe
Pin-Priority: 500
`

var codenameRe = regexp.MustCompile(`^[a-z]+$`)

// osCodename reads the release name, e.g. resolute, from an os-release file.
func osCodename(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if v, ok := strings.CutPrefix(sc.Text(), "VERSION_CODENAME="); ok {
			if v = strings.Trim(v, `"'`); codenameRe.MatchString(v) {
				return v, nil
			}
		}
	}
	return "", errors.New("no release name in " + path)
}

// wifiSources is the additional package source. The security pocket is what unattended-upgrades takes
// updates from, so hostapd stays up to date like everything else.
func wifiSources(codename string) string {
	return fmt.Sprintf(`# Generated by vanilla-router (D-18). Limited to hostapd by /etc/apt/preferences.d/vr-wifi.
Types: deb
URIs: http://archive.ubuntu.com/ubuntu
Suites: %[1]s %[1]s-updates %[1]s-security
Components: universe
Signed-By: /usr/share/keyrings/ubuntu-archive-keyring.gpg
`, codename)
}

// PrepareWiFiPackages writes the package source and the pin. WiFiInstallCommand does the download.
func (a *Applier) PrepareWiFiPackages() error {
	codename, err := osCodename(a.p("/etc/os-release"))
	if err != nil {
		return err
	}
	if err := config.WriteFileAtomic(a.p(wifiPinFile), []byte(wifiPin), 0o644); err != nil {
		return err
	}
	return config.WriteFileAtomic(a.p(wifiSourcesFile), []byte(wifiSources(codename)), 0o644)
}

// WiFiInstallCommand is the fixed command line of the download, without any user input. The package enables
// its own hostapd.service, which is turned off again: vr-hostapd.service runs the access point.
func WiFiInstallCommand() string {
	return "apt-get update -o APT::Update::Error-Mode=any && " +
		"apt-get install -y -o DPkg::Lock::Timeout=600 -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold " +
		strings.Join(WiFiPackages, " ") + " && { systemctl disable --now hostapd.service || true; }"
}

// wifiHealthy checks that the adapter really is an access point. A running service alone says little, hostapd
// only finds out shortly after the start that a channel is not allowed. Without a test mode in hostapd
// (D-18), this check after the start is what triggers the rollback.
func (a *Applier) wifiHealthy(c *config.Config) error {
	out, err := a.Run.Run(nil, "iw", "dev", c.WiFi.Interface, "info")
	if err == nil && strings.Contains(string(out), "type AP") && strings.Contains(string(out), "ssid ") {
		return nil
	}
	log, _ := a.Run.Run(nil, "journalctl", "-u", WiFiUnit, "-n", "3", "-o", "cat", "--no-pager")
	last := strings.Join(strings.Fields(string(log)), " ")
	if last == "" {
		return errors.New("Wi-Fi did not start")
	}
	return fmt.Errorf("Wi-Fi did not start: %s", last)
}

// reloadWiFi turns the access point on or off. It belongs after networkd, because it needs the bridge.
func reloadWiFi(c *config.Config, run func(what string, env []string, name string, args ...string)) {
	if gen.WiFiOn(c) {
		run("wifi", nil, "systemctl", "enable", WiFiUnit)
		run("wifi", nil, "systemctl", "restart", WiFiUnit)
	} else {
		run("wifi", nil, "systemctl", "disable", "--now", WiFiUnit)
	}
}
