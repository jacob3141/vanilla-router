// Package gen generates all service files from a validated configuration (P-04, M2):
// systemd-networkd, nftables, dnsmasq, pppd, hostapd, sysctl, sshd, resolved and unattended-upgrades.
// Generating is a pure function without access to the system, so it can be tested with golden
// files (NF-04). internal/apply does the applying.
package gen

import (
	"fmt"
	"net/netip"
	"path"
	"sort"
	"strings"

	"vanilla-router/internal/config"
)

// Groups determine what is reloaded after a change.
const (
	GroupNetworkd = "networkd"
	GroupLink     = "link" // renaming the ports, only takes effect after a restart
	GroupFirewall = "firewall"
	GroupDNSmasq  = "dnsmasq"
	GroupPPP      = "ppp"
	GroupSysctl   = "sysctl"
	GroupResolved = "resolved"
	GroupSSH      = "ssh"
	GroupAPT      = "apt"
	GroupWiFi     = "wifi"
)

// File is a generated file.
type File struct {
	Path    string
	Mode    uint32
	Group   string
	Content []byte
}

// Managed describes which files belong to vanilla-router. What is there but no longer generated
// is removed by apply (e.g. the VLAN file after switching from PPPoE to DHCP).
var Managed = []struct{ Dir, Glob, Group string }{
	{"/etc/systemd/network", "*-vr-*.link", GroupLink},
	{"/etc/systemd/network", "*-vr-*.netdev", GroupNetworkd},
	{"/etc/systemd/network", "*-vr-*.network", GroupNetworkd},
	{"/etc/vanilla-router/nft", "*.nft", GroupFirewall},
	{"/etc/ppp/peers", "vr-*", GroupPPP},
	{"/etc/vanilla-router/wifi", "*.conf", GroupWiFi},
	{"/etc/sudoers.d", "vr-*", GroupSSH},
}

// Header is in every generated text file.
func header(comment string) string {
	return comment + " Generated by vanilla-router, do not edit by hand.\n" +
		comment + " Make changes through the web interface or /etc/vanilla-router/config.json and `vrctl apply`.\n"
}

// Secrets returns secrets that config.json only refers to (e.g. the PPPoE password).
type Secrets interface {
	Get(ref string) (string, error)
}

// Names are the fixed interface names (PLAN.md 3.4).
const (
	WANIf    = "wan0"
	LANIf    = "lan0"
	LANPort  = "lanp" // lanp1, lanp2 … are the ports in the bridge lan0
	PPPIf    = "ppp0"
	PPPPeers = "vr-wan"
)

// UplinkIf is the interface toward the internet for firewall and prefix delegation.
func UplinkIf(c *config.Config) string {
	if c.WAN.Type == config.WANPPPoE {
		return PPPIf
	}
	return WANIf
}

// pppLowerIf is the interface on which pppd speaks PPPoE (with VLAN: wan0.7).
func pppLowerIf(c *config.Config) string {
	if c.WAN.PPPoE != nil && c.WAN.PPPoE.VLAN > 0 {
		return fmt.Sprintf("%s.%d", WANIf, c.WAN.PPPoE.VLAN)
	}
	return WANIf
}

// lanULA returns the /64 prefix and router address in the home network from the ULA /48 (subnet 1, address ::1).
func lanULA(c *config.Config) (netip.Prefix, netip.Addr, bool) {
	if c.LAN.IPv6.ULA == "" {
		return netip.Prefix{}, netip.Addr{}, false
	}
	p := netip.MustParsePrefix(c.LAN.IPv6.ULA)
	b := p.Addr().As16()
	b[7] = 1 // subnet ID 1
	net64 := netip.PrefixFrom(netip.AddrFrom16(b), 64)
	b[15] = 1
	return net64, netip.AddrFrom16(b), true
}

// Render generates all files. The configuration must be validated (config.Validate).
func Render(c *config.Config, sec Secrets) ([]File, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	var files []File
	add := func(fs ...File) { files = append(files, fs...) }

	add(networkd(c)...)
	add(File{Path: "/etc/vanilla-router/nft/vr.nft", Mode: 0o644, Group: GroupFirewall, Content: []byte(Firewall(c))})
	add(File{Path: "/etc/vanilla-router/dnsmasq.conf", Mode: 0o644, Group: GroupDNSmasq, Content: []byte(DNSmasq(c))})
	ppp, err := pppFiles(c, sec)
	if err != nil {
		return nil, err
	}
	add(ppp...)
	wifi, err := wifiFiles(c, sec)
	if err != nil {
		return nil, err
	}
	add(wifi...)
	add(misc(c)...)

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	for i := 1; i < len(files); i++ {
		if files[i].Path == files[i-1].Path {
			return nil, fmt.Errorf("internal error: %s generated twice", files[i].Path)
		}
	}
	return files, nil
}

// IsManaged reports whether a path belongs to the files managed by vanilla-router.
func IsManaged(p string) (string, bool) {
	for _, m := range Managed {
		if path.Dir(p) != m.Dir {
			continue
		}
		if ok, _ := path.Match(m.Glob, path.Base(p)); ok {
			return m.Group, true
		}
	}
	return "", false
}

// ini writes sections of a systemd file. Empty values are left out.
type ini struct{ b strings.Builder }

func (w *ini) section(name string) { fmt.Fprintf(&w.b, "\n[%s]\n", name) }
func (w *ini) kv(k, v string) {
	if v != "" {
		fmt.Fprintf(&w.b, "%s=%s\n", k, v)
	}
}
func (w *ini) String() string { return w.b.String() }

func yesno(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}
