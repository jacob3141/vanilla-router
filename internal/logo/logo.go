// Package logo describes the project logo (pictogram: a scoop of vanilla ice cream in a cone, two colors)
// as geometry and generates SVG, PNG and the Windows icon from it. That way
// there is only one source and no third-party graphics tools (D-01). The files under docs/ and the
// web interface's favicon are generated with "go run ./internal/logo/mklogo", a test checks that they
// match the code.
package logo

import (
	"fmt"
	"image/color"
	"strings"
)

// The logo's two colors.
var (
	Vanilla = color.NRGBA{0xF0, 0xC8, 0x6A, 0xFF} // scoop, waffle pattern
	Brown   = color.NRGBA{0x8B, 0x5A, 0x2B, 0xFF} // cone; 5.8:1 on white, also good enough for text
)

// Derived colors for interfaces in the logo's style (stick creator).
var (
	Dark  = color.NRGBA{0x4A, 0x30, 0x18, 0xFF} // Text
	Cream = color.NRGBA{0xFD, 0xF3, 0xDC, 0xFF} // light areas
)

// Pt is a point in design space.
type Pt struct{ X, Y float64 }

// Seg is a path command: 'M', 'L', 'C' (three points) or 'Z'.
type Seg struct {
	Op  byte
	Pts []Pt
}

// Path is a path made of segments.
type Path []Seg

// Layer is a layer: fill and/or stroke, optionally clipped to the area of Clip.
type Layer struct {
	Path   Path
	Fill   color.NRGBA // A == 0: no fill
	Stroke color.NRGBA // A == 0: no stroke
	Width  float64
	Clip   Path
	ClipID string
}

// Size is the edge length of the canvas. The design is placed into it with Scale and Offset.
const Size = 256

const (
	scale = 1.08
	offX  = 128 - 128*scale // design x 64…192 centered
	offY  = 128 - 139*scale // design y 34…244 centered
)

func p(x, y float64) Pt { return Pt{x, y} }

// ParsePath reads the short notation "M x y L x y C x y x y x y Z" (absolute commands only).
func ParsePath(s string) Path {
	f := strings.Fields(strings.ReplaceAll(s, ",", " "))
	var out Path
	num := func(i int) float64 {
		var v float64
		if _, err := fmt.Sscan(f[i], &v); err != nil {
			panic("logo: " + f[i])
		}
		return v
	}
	for i := 0; i < len(f); {
		op := f[i][0]
		i++
		n := map[byte]int{'M': 1, 'L': 1, 'C': 3, 'Z': 0}[op]
		s := Seg{Op: op}
		for k := 0; k < n; k++ {
			s.Pts = append(s.Pts, p(num(i), num(i+1)))
			i += 2
		}
		out = append(out, s)
	}
	return out
}

// Layers returns the logo as a pictogram: a circle (scoop) above a triangle (cone), with
// a narrow gap between them. Only the two colors Vanilla and Brown.
func Layers() []Layer {
	const cx, cy, r, k = 128.0, 84.0, 50.0, 0.5523 * 50
	scoop := Path{
		{'M', []Pt{p(cx-r, cy)}},
		{'C', []Pt{p(cx-r, cy-k), p(cx-k, cy-r), p(cx, cy-r)}},
		{'C', []Pt{p(cx+k, cy-r), p(cx+r, cy-k), p(cx+r, cy)}},
		{'C', []Pt{p(cx+r, cy+k), p(cx+k, cy+r), p(cx, cy+r)}},
		{'C', []Pt{p(cx-k, cy+r), p(cx-r, cy+k), p(cx-r, cy)}},
		{'Z', nil},
	}
	cone := ParsePath("M 84 141 L 172 141 L 131 241 C 130 244 126 244 125 241 Z")
	return []Layer{
		{Path: cone, Fill: Brown},
		{Path: scoop, Fill: Vanilla},
	}
}

// tr places a design point on the canvas of size px.
func tr(q Pt, px float64) Pt {
	f := px / Size
	return p((q.X*scale+offX)*f, (q.Y*scale+offY)*f)
}

func hexColor(c color.NRGBA) string { return fmt.Sprintf("#%02x%02x%02x", c.R, c.G, c.B) }

func (pa Path) svg() string {
	var b strings.Builder
	num := func(v float64) string {
		s := fmt.Sprintf("%.2f", v)
		s = strings.TrimRight(strings.TrimRight(s, "0"), ".")
		if s == "-0" {
			s = "0"
		}
		return s
	}
	for i, s := range pa {
		if i > 0 {
			b.WriteByte(' ')
		}
		b.WriteByte(s.Op)
		for _, q := range s.Pts {
			b.WriteString(" " + num(q.X) + " " + num(q.Y))
		}
	}
	return b.String()
}

// SVG returns the logo as SVG (256 × 256, transparent background).
func SVG() []byte {
	var b strings.Builder
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">` + "\n")
	b.WriteString("<!-- vanilla-router, SPDX-License-Identifier: AGPL-3.0-or-later, generated by internal/logo -->\n")
	ls := Layers()
	for _, l := range ls {
		if l.ClipID != "" {
			fmt.Fprintf(&b, `<defs><clipPath id="%s"><path d="%s"/></clipPath></defs>`+"\n", l.ClipID, l.Clip.svg())
		}
	}
	fmt.Fprintf(&b, `<g transform="translate(%.2f %.2f) scale(%.2f)" stroke-linecap="round" stroke-linejoin="round">`+"\n", offX, offY, scale)
	for _, l := range ls {
		attr := `fill="none"`
		if l.Fill.A != 0 {
			attr = `fill="` + hexColor(l.Fill) + `"`
		}
		if l.Stroke.A != 0 {
			attr += fmt.Sprintf(` stroke="%s" stroke-width="%g"`, hexColor(l.Stroke), l.Width)
			if l.Stroke.A != 0xFF {
				attr += fmt.Sprintf(` stroke-opacity="%.2f"`, float64(l.Stroke.A)/255)
			}
		}
		if l.ClipID != "" {
			attr += ` clip-path="url(#` + l.ClipID + `)"`
		}
		fmt.Fprintf(&b, `<path d="%s" %s/>`+"\n", l.Path.svg(), attr)
	}
	b.WriteString("</g>\n</svg>\n")
	return []byte(b.String())
}
