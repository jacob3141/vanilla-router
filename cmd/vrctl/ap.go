// version is set by the build (-ldflags -X).
var version = "dev"

// Role of an access point (docs/sdn-concept.md 3.1): the same package, this file makes the difference.
const roleFile = "/etc/vanilla-router/role-ap"

// baseNetwork gets an address on any wired port until the first bundle arrives. Its number is higher than those of
// the bundle's files, so the bridge from the bundle wins.
const baseNetwork = `# Generated by vanilla-router, do not edit by hand.
[Match]
Type=ether
Kind=!*

[Network]
DHCP=yes
IPv6AcceptRA=yes
`

func cmdAP(args []string) error {
	if len(args) == 0 {
		return fmt.Errorf("usage: vrctl ap enable|run|rollback|status")
	}
	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()
	switch args[0] {
	case "enable":
		return apEnable(ctx)
	case "run":
		fs := flag.NewFlagSet("ap run", flag.ExitOnError)
		dry := fs.String("dry", "", "test: write under this folder and start nothing")
		router := fs.String("router", "", "test: address of the router (host:port)")
		fs.Parse(args[1:])
		a := newAgent()
		if *dry != "" {
			a.Root, a.Dir = *dry, *dry+"/state"
			a.Cmd = apagent.Dry{Log: func(s string) { fmt.Fprintln(os.Stderr, "dry run:", s) }}
			a.Cards, a.MAC, a.Model, a.Hostname = apagent.DryCards, "02:00:00:00:00:60", "Test agent", "test-agent"
			a.Settle, a.Retry = time.Second, 5*time.Second
		}
		if *router != "" {
			a.Routers = func() []string { return []string{*router} }
		}
		return a.Run(ctx)
	case "rollback":
		return newAgent().Rollback(ctx)
	case "status":
		_, err := os.Stat(roleFile)
		fmt.Printf("role access point: %v\n", err == nil)
		return nil
	}
	return fmt.Errorf("unknown command %q", args[0])
}

func newAgent() *apagent.Agent {
	host, _ := os.Hostname()
	mac, model := apagent.Uplink()
	sys := apagent.System{}
	return &apagent.Agent{Cmd: sys, Hostname: host, Model: model, MAC: mac, Version: version, Show: showOnScreen,
		Log:   slog.New(slog.NewTextHandler(os.Stderr, nil)),
		Cards: func(c context.Context) []gen.RadioCaps { return apagent.Cards(c, sys) },
		Routers: func() []string {
			port := strconv.Itoa(apd.Port)
			out := []string{}
			if gw := apagent.Gateway(); gw != "" {
				out = append(out, net.JoinHostPort(gw, port))
			}
			return append(out, net.JoinHostPort("router.home.arpa", port))
		},
	}
}

// showOnScreen writes to the journal and the computer's screen: an AP usually has only that (concept 4.3).
func showOnScreen(s string) {
	fmt.Fprintln(os.Stderr, s)
	if f, err := os.OpenFile("/dev/tty1", os.O_WRONLY, 0); err == nil {
		fmt.Fprintf(f, "\r\n%s\r\n", s)
		f.Close()
	}
}

// apEnable turns a computer with Ubuntu Server and this package into an access point.
func apEnable(ctx context.Context) error {
	if os.Geteuid() != 0 {
		return fmt.Errorf("please run as root")
	}
	if _, err := os.Stat(config.Path); err == nil {
		return fmt.Errorf("this computer is set up as a router (%s exists)", config.Path)
	}
	if err := applier().PrepareWiFiPackages(); err != nil {
		return err
	}
	run := apagent.System{}
	if out, err := run.Run(ctx, "sh", "-c", apply.WiFiInstallCommand()); err != nil {
		return fmt.Errorf("Wi-Fi software: %v: %s", err, strings.TrimSpace(out))
	}
	if err := config.WriteFileAtomic("/etc/systemd/network/80-vr-ap-base.network", []byte(baseNetwork), 0o644); err != nil {
		return err
	}
	if err := config.WriteFileAtomic(roleFile, []byte("access point\n"), 0o644); err != nil {
		return err
	}
	// Services of the router role may be missing or already off, that is fine
	run.Run(ctx, "systemctl", "disable", "--now", "vr-webui.service", "vr-webui-helper.service", "vr-apd.service", "vr-dnsmasq.service", "vr-firewall.service")
	for _, c := range [][]string{
		{"systemctl", "enable", "systemd-networkd.service"},
		{"networkctl", "reload"},
		{"systemctl", "enable", "--now", "vr-ap.service"},
	} {
		if out, err := run.Run(ctx, c[0], c[1:]...); err != nil {
			return fmt.Errorf("%s: %v: %s", strings.Join(c, " "), err, strings.TrimSpace(out))
		}
	}
	fmt.Println("This computer is now an access point. Open the router's web interface and compare the code on this screen.")
	return nil
}
